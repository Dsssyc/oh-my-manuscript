export const WEB_MESSAGES = { en, "zh-CN": zhCN };

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translate(locale: Locale): Translate {
  return (key, values = {}) => WEB_MESSAGES[locale][key].replace(
    /\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder),
  );
}

export function detectBrowserLocale(): Locale {
  const param = new URLSearchParams(window.location.search).get("lang");
  if (param === "en" || param === "zh-CN") return param;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
